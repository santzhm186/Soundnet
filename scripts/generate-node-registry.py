#!/usr/bin/env python3
"""Discover nodes/*/Node.hpp. Never hand-edit the generated registry.

Every descriptor declares // soundnet-module: namespace.key and an optional
// soundnet-order: integer. Its function is tri::nodes::<folder_slug>::module().
"""
import argparse
import os
import tempfile
from pathlib import Path
import re
import sys


def generate(root):
    entries=[]
    adapter_file=root/'nodes/_legacy/adapter-keys.txt'
    adapters={line.strip() for line in adapter_file.read_text().splitlines() if line.strip() and not line.startswith('#')} if adapter_file.exists() else set()
    keys=set()
    namespaces=set()
    for path in sorted((root/'nodes').glob('*/Node.hpp')):
        if path.parent.name.startswith('_'):
            continue
        text=path.read_text()
        match=re.search(r'^// soundnet-module: ([a-z0-9][a-z0-9_.-]+)$',text,re.M)
        if not match:
            raise ValueError(f'{path}: missing soundnet-module declaration')
        key=match[1]
        if '.' not in key or key in keys:
            raise ValueError(f'{path}: duplicate or unnamespaced node key {key}')
        keys.add(key)
        slug=path.parent.name
        if not re.fullmatch(r'[a-z][a-z0-9_-]*',slug):
            raise ValueError(f'{path}: invalid module directory')
        ns=slug.replace('-','_')
        if ns in namespaces:
            raise ValueError(f'{path}: duplicate module namespace {ns}')
        namespaces.add(ns)
        order=re.search(r'^// soundnet-order: (\d+)$',text,re.M)
        entries.append((int(order[1]) if order else 10000,key,slug,ns))
    entries.sort()
    lines=['#pragma once','// Generated by scripts/generate-node-registry.py. Do not edit.']
    lines += [f'#include "{slug}/Node.hpp"' for _,_,slug,_ in entries]
    lines += ['', 'namespace tri {', 'inline const std::vector<NodeModule>& nodeModules() {',
              '    static const std::vector<NodeModule> modules=[] {',
              '        std::vector<NodeModule> result;',
              '        auto add=[&](const char* key,bool legacyAllowed,NodeModule module) {',
              '            if(!module.spec.key || std::strcmp(key,module.spec.key)!=0)',
              '                throw std::logic_error("Module identity differs from its discovery declaration");',
              '            if(module.spec.legacyAdapter && !legacyAllowed)',
              '                throw std::logic_error("New node modules cannot opt into the legacy adapter");',
              '            result.push_back(std::move(module));',
              '        };']
    lines += [f'        add("{key}",{str(key in adapters).lower()},nodes::{ns}::module());' for _,key,_,ns in entries]
    lines += ['        return result;','    }();','    return modules;','}','} // namespace tri','']
    return '\n'.join(lines),len(entries)


def generate_editors(root):
    entries=[]
    for path in sorted((root/'nodes').glob('*/Editor.hpp')):
        descriptor=path.parent/'Node.hpp'
        if path.parent.name.startswith('_') or not descriptor.exists():
            continue
        match=re.search(r'^// soundnet-module: ([a-z0-9][a-z0-9_.-]+)$',descriptor.read_text(),re.M)
        if not match:
            raise ValueError(f'{descriptor}: editor has no node identity')
        entries.append((match[1],path.parent.name,path.parent.name.replace('-','_')))
    lines=['#pragma once','// Generated by scripts/generate-node-registry.py. UI targets only.',
           '#include "../platform/NodeEditor.h"','#include <cstring>']
    lines += [f'#include "{slug}/Editor.hpp"' for _,slug,_ in entries]
    lines += ['', 'namespace tri {', 'inline NodeEditorFactory nodeEditorFactory(const char* key) {',
              '    if(!key)return nullptr;']
    lines += [f'    if(std::strcmp(key,"{key}")==0)return nodes::{ns}::editor;' for key,_,ns in entries]
    lines += ['    return nullptr;','}','} // namespace tri','']
    return '\n'.join(lines)


def atomic_write(target,text):
    descriptor,temporary=tempfile.mkstemp(prefix=target.name+'.',dir=target.parent)
    try:
        os.fchmod(descriptor,0o644)
        with os.fdopen(descriptor,'w') as output:output.write(text)
        os.replace(temporary,target)
    finally:
        if os.path.exists(temporary):os.unlink(temporary)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
    args=parser.parse_args()
    try:
        result,count=generate(args.root)
        editors=generate_editors(args.root)
    except (OSError,ValueError) as error:
        print(error,file=sys.stderr)
        return 1
    for name,text in [('GeneratedRegistry.hpp',result),('GeneratedEditors.hpp',editors)]:
        target=args.root/'nodes'/name
        if args.check:
            if not target.exists() or target.read_text()!=text:
                print('Node registry is stale. Run scripts/generate-node-registry.py.',file=sys.stderr)
                return 1
        elif not target.exists() or target.read_text()!=text:
            atomic_write(target,text)
    print(f'PASS: {count} independently registered node modules')
    return 0

if __name__=='__main__':
    sys.exit(main())
